"""Make a requirements file that pins the book's packages to Colab's versions.

Google publishes the packages installed in Colab's runtime in
https://github.com/googlecolab/backend-info. This script keeps only the
packages the book uses, so CI installs what Colab has and nothing more:
a notebook that needs anything else has to install it itself.

Usage: python ci/colab_requirements.py > ci/requirements-colab.txt
"""

import datetime
import re
import sys
from urllib.request import urlopen

FREEZE_URL = "https://raw.githubusercontent.com/googlecolab/backend-info/main/pip-freeze.txt"

# Packages the notebooks import that Colab provides, plus the kernel
PACKAGES = [
    "ipykernel",
    "ipython",
    "matplotlib",
    "networkx",
    "numpy",
    "pandas",
    "pydot",
    "scikit-image",
    "scipy",
    "shapely",
    "statsmodels",
    "sympy",
    "tables",
]


def normalize(name):
    """Normalize a package name as pip does (PEP 503)."""
    return re.sub(r"[-_.]+", "-", name).lower()


def main():
    text = urlopen(FREEZE_URL).read().decode()
    pins = {}
    for line in text.splitlines():
        match = re.match(r"^([A-Za-z0-9_.-]+)==(\S+)$", line.strip())
        if match:
            pins[normalize(match.group(1))] = match.group(2)

    missing = [p for p in PACKAGES if normalize(p) not in pins]
    if missing:
        sys.exit(f"Not in Colab's pip freeze: {missing}")

    print(f"# Generated by ci/colab_requirements.py on {datetime.date.today()}")
    print(f"# from {FREEZE_URL}")
    for package in PACKAGES:
        print(f"{package}=={pins[normalize(package)]}")


if __name__ == "__main__":
    main()
